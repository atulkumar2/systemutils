#!/bin/bash
# setup-env.sh — create wifi-monitor/.env from detected machine defaults.
#
# Usage:
#   ./setup-env.sh [--force] [--iface NAME] [--user LOGIN]
#
# With no flags it prompts interactively, offering auto-detected defaults
# (default-route interface and current login user). Flags skip the prompts.
# Existing .env is kept unless --force is given (or overwrite is confirmed).
#
# The generated .env is git-ignored (see .gitignore) — never commit it.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$SCRIPT_DIR/.env"

FORCE=0
FLAG_IFACE=""
FLAG_USER=""

usage() {
    sed -n '2,11p' "${BASH_SOURCE[0]}" | sed 's/^# \?//'
}

while [ $# -gt 0 ]; do
    case "$1" in
        -f|--force) FORCE=1; shift ;;
        --iface) FLAG_IFACE="${2:?--iface needs a value}"; shift 2 ;;
        --iface=*) FLAG_IFACE="${1#--iface=}"; shift ;;
        --user) FLAG_USER="${2:?--user needs a value}"; shift 2 ;;
        --user=*) FLAG_USER="${1#--user=}"; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown option: $1 (try --help)" >&2; exit 1 ;;
    esac
done

# --- defaults ---------------------------------------------------------------
DEFAULT_IFACE="$(ip -o -4 route show to default 2>/dev/null | awk '{print $5}' | head -n1)"
[ -z "$DEFAULT_IFACE" ] && DEFAULT_IFACE="wlp5s0"

DEFAULT_USER="${SUDO_USER:-}"
[ -z "$DEFAULT_USER" ] && DEFAULT_USER="$(logname 2>/dev/null || true)"
[ -z "$DEFAULT_USER" ] && DEFAULT_USER="$(id -un)"

# --- existing .env ----------------------------------------------------------
if [ -f "$ENV_FILE" ] && [ "$FORCE" -eq 0 ]; then
    if [ -t 0 ]; then
        read -r -p ".env already exists. Overwrite? [y/N] " ANSWER
        [[ "$ANSWER" =~ ^[Yy]$ ]] || { echo "Kept existing .env."; exit 0; }
    else
        echo ".env already exists. Re-run with --force to overwrite." >&2
        exit 1
    fi
fi

# --- values (flags win, otherwise prompt with default) -----------------------
prompt() { # $1: message, $2: default — echoes result
    local msg="$1" def="$2" val
    if [ -t 0 ]; then
        read -r -p "$msg [$def]: " val
        echo "${val:-$def}"
    else
        echo "$def"
    fi
}

if [ -n "$FLAG_IFACE" ]; then WIFI_IFACE="$FLAG_IFACE"
else WIFI_IFACE="$(prompt "Wi-Fi interface" "$DEFAULT_IFACE")"; fi

if [ -n "$FLAG_USER" ]; then NOTIFY_USER="$FLAG_USER"
else NOTIFY_USER="$(prompt "Login username (desktop notifications)" "$DEFAULT_USER")"; fi

LOG_FILE="$(prompt "Log file" "/var/log/wifi_band.log")"
BAND_STATE_FILE="$(prompt "Band state file" "/var/tmp/wifi_last_band")"
COUNTER_STATE_FILE="$(prompt "Byte-counter state file" "/var/tmp/wifi_byte_counters")"
LOCK_FILE="$(prompt "Lock file" "/var/lock/wifi_usage.lock")"
USAGE_LOGGER_BIN="$(prompt "Installed logger path" "/usr/local/bin/wifi_usage_logger.sh")"

# --- sanity checks (warnings only; install.sh validates strictly) ------------
[ -d "/sys/class/net/$WIFI_IFACE" ] \
    || echo "Warning: interface '$WIFI_IFACE' not found under /sys/class/net." >&2
id -u "$NOTIFY_USER" >/dev/null 2>&1 \
    || echo "Warning: user '$NOTIFY_USER' does not exist (install.sh needs a valid login)." >&2

# --- write ------------------------------------------------------------------
cat > "$ENV_FILE" <<EOF
# Generated by setup-env.sh — machine-specific, do not commit (git-ignored).
WIFI_IFACE=$WIFI_IFACE
NOTIFY_USER=$NOTIFY_USER
LOG_FILE=$LOG_FILE
BAND_STATE_FILE=$BAND_STATE_FILE
COUNTER_STATE_FILE=$COUNTER_STATE_FILE
LOCK_FILE=$LOCK_FILE
USAGE_LOGGER_BIN=$USAGE_LOGGER_BIN
EOF
chmod 600 "$ENV_FILE"

echo "Wrote $ENV_FILE"
echo "Next: ./install.sh"
